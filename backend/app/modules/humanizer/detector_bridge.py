"""Мост к ИИ-детектору автора.

Ключевой урок калибровки: **перед оценкой из текста надо снять
markdown-разметку.**

Первое измерение дало AUC 0.375 — детектор работал хуже монетки и в
обратную сторону. Причина оказалась не в нём: тексты человека пришли
из PDF (разметка потеряна при извлечении), а тексты моделей — из API
с `**жирным**`, заголовками `##` и списками. Детектор honestly считал
markdown-метрики (K2 «Оформление») и по ним разделял источник данных,
а не авторство.

После снятия разметки на той же выборке AUC стал 0.893.

Это общее правило для всей системы: сравнивать тексты можно только
приведёнными к одному виду. Наш генератор выдаёт markdown, поэтому
перед любой стилевой проверкой разметку снимаем.
"""

from __future__ import annotations

import re

RE_BOLD = re.compile(r"\*\*|__")
RE_HEADING = re.compile(r"(?m)^#{1,6}\s*")
RE_BULLET = re.compile(r"(?m)^\s*[-*+]\s+")
RE_CODE = re.compile(r"`+")
RE_BLANKS = re.compile(r"\n{3,}")


def strip_markdown(text: str) -> str:
    """Снимает разметку, сохраняя сам текст и пунктуацию.

    Списки превращаются в обычные строки: маркер убирается, содержимое
    остаётся. Нумерованные списки не трогаем — цифры встречаются и в
    живом тексте, а их удаление исказило бы предложения.
    """
    if not text:
        return ""
    out = RE_BOLD.sub("", text)
    out = RE_HEADING.sub("", out)
    out = RE_BULLET.sub("", out)
    out = RE_CODE.sub("", out)
    out = RE_BLANKS.sub("\n\n", out)
    return out.strip()


