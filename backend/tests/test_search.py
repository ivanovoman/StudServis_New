"""Проверки лексического поиска: стеммер, токенизация, BM25."""

from __future__ import annotations

import pytest

from app.modules.rag_service.search import (
    Document,
    SearchIndex,
    stem,
    tokenize,
)


@pytest.mark.parametrize(
    "forms",
    [
        ["коллизия", "коллизии", "коллизией", "коллизиями", "коллизий"],
        ["норма", "нормы", "нормами", "норме", "норм"],
        ["специальный", "специальная", "специальные", "специального"],
        ["подрядчик", "подрядчика", "подрядчику", "подрядчиками"],
        ["право", "права", "праве", "правом", "правами"],
    ],
)
def test_падежи_одного_слова_сходятся_к_одной_основе(forms: list[str]):
    """Иначе поиск по «коллизии» не найдёт абзац про «коллизию»."""
    assert len({stem(f) for f in forms}) == 1


@pytest.mark.parametrize("word", ["иск", "суд", "акт", "дело"])
def test_короткое_слово_не_съедается_целиком(word: str):
    """Отрезание окончаний у коротких слов оставляло пустую строку."""
    assert len(stem(word)) >= 3


def test_стоп_слова_выбрасываются():
    tokens = tokenize("Это и есть тот самый случай, когда норма не работает")
    assert "норм" in tokens
    assert "это" not in tokens
    assert "когда" not in tokens


def test_ё_приводится_к_е():
    assert stem("объём") == stem("объем")


def _index() -> SearchIndex:
    index = SearchIndex()
    index.add([
        Document(id="коллизия", text=(
            "Юридическая коллизия — противоречие между двумя формально "
            "действующими нормами, которые предписывают взаимоисключающее "
            "поведение в одном и том же отношении.")),
        Document(id="пробел", text=(
            "Пробел в праве означает отсутствие нормы, регулирующей "
            "отношение. При пробеле применяется аналогия закона.")),
        Document(id="подряд", text=(
            "По договору подряда подрядчик обязуется выполнить работу по "
            "заданию заказчика и сдать её результат.")),
        Document(id="техника", text=(
            "Дефекты законодательной техники возникают при бессистемном "
            "обновлении правовых актов без отмены устаревших.")),
    ])
    return index


def test_находит_по_смыслу_запроса():
    hits = _index().search("что такое пробел в праве", limit=1)

    assert hits
    assert hits[0].document.id == "пробел"


def test_родственные_слова_находятся_по_началу_основы():
    """«законы» и «законодательная» — разные основы, но одно гнездо.

    Точное совпадение в другом документе может перевесить, и это
    правильно; важно, что родственное слово вообще попадает в выдачу,
    а не отсекается.
    """
    hits = _index().search("ошибки в подготовке законов", limit=4)
    found = [h.document.id for h in hits]

    assert "техника" in found


def test_пустой_запрос_не_роняет_поиск():
    assert _index().search("") == []
    assert _index().search("и в на") == []


def test_поиск_по_пустому_индексу():
    assert SearchIndex().search("что угодно") == []


def test_фрагмент_без_значимых_слов_не_индексируется():
    index = SearchIndex()
    added = index.add([
        Document(id="мусор", text="— — — 12 ..."),
        Document(id="нормальный", text="Коллизия норм разрешается судом."),
    ])

    assert added == 1
    assert len(index) == 1


def test_сниппет_показывает_место_совпадения():
    long_text = (
        "Вводная часть документа, не относящаяся к делу. " * 10
        + "Оригинальность работы должна составлять не менее шестидесяти "
          "процентов по системе Антиплагиат. "
        + "Заключительная часть документа. " * 10
    )
    index = SearchIndex()
    index.add([Document(id="d", text=long_text)])

    hit = index.search("какая нужна оригинальность", limit=1)[0]
    snippet = index.snippet(hit, "какая нужна оригинальность", width=200)

    assert "ригинальность" in snippet
    assert len(snippet) <= 220


def test_ранжирование_по_частоте_и_редкости():
    index = SearchIndex()
    index.add([
        Document(id="мимо", text="Коллизия упомянута здесь однажды."),
        Document(id="точно", text=(
            "Виндикационный иск — иск невладеющего собственника к "
            "владеющему несобственнику. Виндикация применяется при "
            "утрате владения вещью.")),
    ])

    hits = index.search("виндикация", limit=2)
    assert hits[0].document.id == "точно"


def test_источники_перечисляются():
    index = SearchIndex()
    index.add([
        Document(id="1", text="Норма права и её структура.", source="а.pdf"),
        Document(id="2", text="Отрасли права и институты.", source="б.pdf"),
    ])

    assert index.sources == ["а.pdf", "б.pdf"]
