const test = require('node:test');
const assert = require('node:assert');
const { splitPieces, polishDraft, styleRules } = require('../api/polish.js');

// --- нарезка --------------------------------------------------------

test('точка в сокращении не рвёт предложение', () => {
  const text = 'Согласно ст. 15 ГК РФ договор обязателен. '
    + 'Это следует из п. 2 указанной нормы.';
  const pieces = splitPieces(text, 10, 200);
  assert.ok(!pieces.some((p) => p.trim().endsWith('ст.')),
    'кусок не должен обрываться на сокращении');
});

test('десятичное число не рвёт предложение', () => {
  const pieces = splitPieces('Доля выросла до 12.5 процента за год.', 5, 100);
  assert.strictEqual(pieces.length, 1);
});

test('куски держатся в заданных границах', () => {
  const sentence = 'Коллизия норм права возникает при противоречии предписаний. ';
  const pieces = splitPieces(sentence.repeat(30), 350, 500);
  // Последний кусок может быть коротким — это остаток.
  for (const piece of pieces.slice(0, -1)) {
    assert.ok(piece.length >= 350, `кусок короче нижней границы: ${piece.length}`);
    assert.ok(piece.length <= 500 + sentence.length,
      `кусок длиннее верхней границы: ${piece.length}`);
  }
});

test('пустой текст не ломает нарезку', () => {
  assert.deepStrictEqual(splitPieces(''), []);
  assert.deepStrictEqual(splitPieces(null), []);
});

// --- сторожа --------------------------------------------------------

const ДЛИННЫЙ = 'Коллизия норм права возникает тогда, когда два предписания '
  + 'равной силы по-разному решают один вопрос, и правоприменитель обязан '
  + 'выбрать между ними, опираясь на правила преодоления противоречий. '
  + 'Согласно ст. 76 Конституции РФ приоритет принадлежит федеральному '
  + 'закону [1]. Эта мысль развивается и в доктрине, где отмечается '
  + 'необходимость учитывать предмет ведения при разрешении спора норм. '
  + 'Практика идёт тем же путём, признавая иерархию актов решающим доводом.';

test('потерянная норма вызывает перепись на бис', async () => {
  let попытка = 0;
  const ask = async () => {
    попытка += 1;
    // Первый ответ теряет ссылку на статью, второй — возвращает.
    return попытка === 1
      ? 'Коллизия возникает при противоречии предписаний равной силы, и выбор делает правоприменитель по правилам преодоления [1]. Приоритет принадлежит федеральному закону, что подтверждается и доктриной, и практикой применения норм в спорных случаях сегодня.'
      : ДЛИННЫЙ;
  };

  const r = await polishDraft(ДЛИННЫЙ, { ask });
  assert.strictEqual(r.retries, 1, 'должна быть одна перепись на бис');
  assert.deepStrictEqual(r.lost, [], 'норма должна вернуться');
});

test('потерянная ссылка на источник тоже вызывает перепись', async () => {
  let попытка = 0;
  const ask = async () => {
    попытка += 1;
    return попытка === 1
      ? ДЛИННЫЙ.replace(' [1]', '')
      : ДЛИННЫЙ;
  };

  const r = await polishDraft(ДЛИННЫЙ, { ask });
  assert.strictEqual(r.retries, 1);
  assert.deepStrictEqual(r.droppedRefs, []);
});

test('если вернуть фактуру не удалось, берётся черновик', async () => {
  // Модель упорно теряет статью — лучше корявый черновик, чем
  // рассуждение без нормы, на которую оно опирается.
  const ask = async () => 'Коллизия возникает при противоречии предписаний равной силы, и выбор делает правоприменитель, опираясь на правила преодоления таких противоречий в спорных случаях [1].';

  const r = await polishDraft(ДЛИННЫЙ, { ask });
  assert.strictEqual(r.fallbacks, 1);
  assert.ok(r.text.includes('ст. 76'), 'норма должна остаться в тексте');
});

test('усохший кусок вызывает перепись с точными числами', async () => {
  let запрос = '';
  let попытка = 0;
  const ask = async (messages) => {
    попытка += 1;
    if (попытка === 2) запрос = messages[1].content;
    return попытка === 1 ? 'Коротко про коллизию [1] и ст. 76.' : ДЛИННЫЙ;
  };

  const r = await polishDraft(ДЛИННЫЙ, { ask });
  assert.strictEqual(r.retries, 1);
  assert.ok(/\d+ знаков/.test(запрос),
    'в требовании должны стоять числа, а не просьба «тот же объём»');
});

test('хороший ответ переписей не вызывает', async () => {
  const ask = async () => ДЛИННЫЙ;
  const r = await polishDraft(ДЛИННЫЙ, { ask });
  assert.strictEqual(r.retries, 0);
  assert.strictEqual(r.fallbacks, 0);
  assert.deepStrictEqual(r.lost, []);
});

test('о ходе работы сообщается по кускам', async () => {
  const шаги = [];
  const ask = async () => ДЛИННЫЙ;
  await polishDraft(ДЛИННЫЙ, { ask, onPiece: (i, n) => шаги.push(`${i}/${n}`) });
  assert.ok(шаги.length > 0);
  assert.match(шаги[шаги.length - 1], /^(\d+)\/\1$/, 'последний шаг — последний кусок');
});

test('без модели перепись не запускается', async () => {
  await assert.rejects(() => polishDraft('текст', {}), /нужен ask/);
});

// --- правила стиля --------------------------------------------------

test('образцы попадают в правила стиля', () => {
  const rules = styleRules(['Первый отрывок.', 'Второй отрывок.']);
  assert.ok(rules.includes('ОТРЫВОК 1'));
  assert.ok(rules.includes('Второй отрывок.'));
});

test('без образцов правила всё равно работают', () => {
  const rules = styleRules([]);
  assert.ok(rules.includes('РАЗНОЙ длины'));
});
