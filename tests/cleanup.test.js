'use strict';

/**
 * Чистка вывода модели: оговорки GigaChat и место завершающей связки.
 * Фразы — из курсовой заказчика о Следственном комитете.
 */

const test = require('node:test');
const assert = require('node:assert');
const { stripDisclaimers, hasDisclaimer, splitTail, appendBeforeTail } = require('../api/cleanup');

const D1 = 'Генеративные языковые модели не обладают собственным мнением – их ответы являются обобщением информации, находящейся в открытом доступе. Чтобы избежать ошибок и неправильного толкования, разговоры на чувствительные темы могут быть ограничены.';
const D2 = 'К сожалению, иногда генеративные языковые модели могут создавать некорректные ответы, основанные на открытых источниках. Во избежание неправильного толкования, ответы на вопросы, связанные с чувствительными темами, временно ограничены. Благодарим за понимание.';
const D3 = 'Как и любая языковая модель, GigaChat не обладает собственным мнением и не транслирует мнение своих разработчиков. Во избежание неправильного толкования, разговоры на некоторые темы временно ограничены.';

test('оговорка, приклеенная без пробела к целому абзацу, срезается, абзац цел', () => {
  const par = 'Это требует особой стрессоустойчивости. Это становится критерием при ротации кадров [5].' + D1;
  const r = stripDisclaimers(`Первый абзац о кадрах.\n\n${par}`);
  assert.strictEqual(r.text, 'Первый абзац о кадрах.\n\nЭто требует особой стрессоустойчивости. Это становится критерием при ротации кадров [5].');
  assert.strictEqual(r.removed.length, 1);
  assert.ok(!hasDisclaimer(r.text));
});

test('оговорка посреди фразы: «Как отмечает О.И.К сожалению…» — уходит и оборванная фраза', () => {
  const par = 'Специфика новых регионов диктует особые требования. Требования касаются гуманитарной работы. Как отмечает О.И.' + D2;
  const r = stripDisclaimers(par);
  assert.strictEqual(r.text, 'Специфика новых регионов диктует особые требования. Требования касаются гуманитарной работы.');
});

test('от абзаца остался один зачин — абзац убирается целиком', () => {
  const r = stripDisclaimers('Целый абзац. Ещё фраза.\n\nПрактика работы новых территорий также диктует свои контуры развития.' + D3);
  assert.strictEqual(r.text, 'Целый абзац. Ещё фраза.');
  assert.ok(r.removed[0].startsWith('Практика работы'));
});

test('текст без оговорок не меняется ни на символ', () => {
  const t = 'Статья 151 УПК РФ распределяет подследственность.\n\nОбвинение утверждает прокурор (ст. 221 УПК РФ).';
  assert.deepStrictEqual(stripDisclaimers(t), { text: t, removed: [] });
});

const BODY = 'Абзац первый о статусе. Он длинный.\n\nАбзац второй о принципах. Он тоже длинный.';

test('связка последней фразой абзаца: добор встаёт перед ней', () => {
  const text = `${BODY} Теперь логично перейти к кадровой политике.`;
  const out = appendBeforeTail(text, 'Помимо общих принципов, закон закрепляет и узкие правила.');
  assert.strictEqual(out, 'Абзац первый о статусе. Он длинный.\n\nАбзац второй о принципах. Он тоже длинный.\n\n'
    + 'Помимо общих принципов, закон закрепляет и узкие правила.\n\nТеперь логично перейти к кадровой политике.');
});

test('итоговый абзац «Таким образом…» остаётся последним', () => {
  const text = `${BODY}\n\nТаким образом, статус СКР – гибрид. Разобравшись с ним, логично перейти к кадрам.`;
  const out = appendBeforeTail(text, 'Ещё один аспект – правосубъектность ведомства.');
  assert.ok(out.endsWith('Таким образом, статус СКР – гибрид. Разобравшись с ним, логично перейти к кадрам.'));
  assert.ok(out.indexOf('Ещё один аспект') < out.indexOf('Таким образом'));
});

test('у добора своя связка, у раздела уже есть — вторая не дублируется', () => {
  const text = `${BODY} Теперь нужно спуститься от истории к букве закона.`;
  const out = appendBeforeTail(text, 'Помимо этого, практика показала казус. Теперь логично перейти к закону № 403-ФЗ.');
  assert.strictEqual((out.match(/Теперь/g) || []).length, 1);
  assert.ok(out.endsWith('Теперь нужно спуститься от истории к букве закона.'));
});

test('без связки добор просто дописывается в конец', () => {
  assert.strictEqual(appendBeforeTail(BODY, 'Третий абзац.'), `${BODY}\n\nТретий абзац.`);
  assert.deepStrictEqual(splitTail(BODY), { body: BODY, tail: '' });
});

const { fixMixedScript } = require('../api/cleanup');

test('латинская «a» в русском слове заменяется, английские слова и аббревиатуры целы', () => {
  const r = fixMixedScript('Дела об убийствa ведёт СК; KPI, quid pro quo и IT-экспертизы не трогаем.');
  assert.strictEqual(r.text, 'Дела об убийства ведёт СК; KPI, quid pro quo и IT-экспертизы не трогаем.');
  assert.strictEqual(r.fixed, 1);
});

const { relocateTransitions } = require('../api/cleanup');

test('ремонт: итоговый абзац из середины встаёт в конец раздела', () => {
  const sec = 'Зачин о статусе. Ещё фраза.\n\nТаким образом, статус СКР – гибрид. Разобравшись с этим, логично перейти к кадрам.\n\n'
    + 'Помимо общих принципов, закон закрепляет узкие правила.\n\nЕщё один аспект – правосубъектность.';
  const r = relocateTransitions(sec);
  assert.strictEqual(r.moved, 1);
  assert.ok(r.text.endsWith('Таким образом, статус СКР – гибрид. Разобравшись с этим, логично перейти к кадрам.'));
});

test('ремонт: у раздела своя связка в конце — переход из середины убран, содержание сохранено', () => {
  const sec = 'Зачин. Фраза.\n\nИменно этот клубок распутали в 2011 году. Теперь нужно перейти к букве закона.\n\n'
    + 'Однако выделение не решило проблем.\n\nЭтот акцент связан с кадрами. Теперь логично перейти к закону № 403-ФЗ.';
  const r = relocateTransitions(sec);
  assert.strictEqual((r.text.match(/Теперь/g) || []).length, 1);
  assert.ok(r.text.includes('Именно этот клубок распутали в 2011 году.'));
  assert.ok(r.text.endsWith('Теперь логично перейти к закону № 403-ФЗ.'));
});
