test('рецензент: цитата без кавычек, «замену» с опечаткой, отказы «не выписывать»', () => {
  const text = 'Отказ ставит крест на карьере сотрудника. Это создает почву для споров. Принят «брак» в работе. Возникает размывание ответственности.';
  const answer = 'ставит крест на карьере сотрудника — фразеологизм — негативно влияет на карьеру сотрудника\n'
    + '«Принят «брак» в работе» — разговорное — принята некачественная работа\n'
    + '«размывание ответственности» — устоявшееся выражение практики, не выписывать.\n'
    + '«создает почву для споров» — метафора, научная замену: создает условия для споров';
  const got = parseReview(answer, text).map((h) => h.match);
  assert.ok(got.includes('ставит крест на карьере сотрудника'));
  assert.ok(!got.some((m) => /размывание/.test(m)));
  assert.ok(!got.some((m) => /почву/.test(m)));   // «почва для» — оборот автора
});

