test('рецензент: разбирает ответ в трёх форматах модели', () => {
  const text = 'Корень противоречий кроется в законе. Механизм часто буксует. Суд оказывается заложником спора.';
  const answer = '«Корень противоречий кроется» — метафора, научная замена: «Источник противоречий заключается»\n'
    + '«часто буксует» — разговорное — нередко не действует\n'
    + '«оказывается заложником спора» → «зависит от исхода спора»\n'
    + 'Пояснение без цитаты.\n'
    + '«чего нет в тексте» — метафора — замена';
  const got = parseReview(answer, text);
  assert.deepStrictEqual(got.map((h) => h.match),
    ['Корень противоречий кроется', 'часто буксует', 'оказывается заложником спора']);
  assert.strictEqual(got[0].hint, 'Источник противоречий заключается');
  assert.strictEqual(got[1].hint, 'нередко не действует');
  assert.strictEqual(got[2].hint, 'зависит от исхода спора');
  assert.match(got[0].kind, /метафора/);
});

