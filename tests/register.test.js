test('перепись: длинный текст уходит пачками, каждая со своей нумерацией', async () => {
  const many = Array.from({ length: 20 }, (_, i) => `Раздел ${i + 1} тянут на себе следователи.`).join(' ');
  const calls = [];
  const ask = async (messages) => {
    const lines = messages[1].content.split('\n').filter((l) => /^\d+\)/.test(l));
    calls.push(lines.length);
    return lines.map((l) => l.replace('тянут на себе', 'обеспечивают')).join('\n');
  };
  const r = await fixRegister(many, ask);
  assert.deepStrictEqual(calls, [15, 5]);
  assert.strictEqual(r.fixed, 20);
  assert.ok(!/тянут/.test(r.text));
});

