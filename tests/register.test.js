const TEXT = 'Взыскание идет в порядке ст. 46 НК РФ [3]. '
  + 'Законодателю стоило бы установить жесткий срок для такой замены. '
  + 'Отдельная головная боль – взыскание с индивидуальных предпринимателей.';

test('перепись: меняет только предложения с находками', async () => {
  let seen = '';
  const ask = async (messages) => {
    seen = messages[1].content;
    return '1) Законодателю целесообразно установить жесткий срок для такой замены.\n'
      + '2) Отдельную проблему составляет взыскание с индивидуальных предпринимателей.';
  };
  const r = await fixRegister(TEXT, ask);
  assert.strictEqual(r.found, 2);
  assert.strictEqual(r.fixed, 2);
  assert.deepStrictEqual(r.left, []);
  assert.ok(r.text.startsWith('Взыскание идет в порядке ст. 46 НК РФ [3].'));
  assert.ok(r.text.includes('целесообразно установить'));
  // Чистое предложение модели не отдавали.
  assert.ok(!seen.includes('ст. 46'));
  // Подсказка ушла вместе с предложением.
  assert.ok(seen.includes('«стоило бы» → «целесообразно»'));
});

test('перепись: замену, потерявшую норму, не принимает', async () => {
  const src = 'Автоматика ФНС списывает средства по ст. 46 НК РФ.';
  let calls = 0;
  const ask = async () => {
    calls += 1;
    return '1) Автоматизированные системы ФНС списывают средства.';   // норма потеряна
  };
  const r = await fixRegister(src, ask);
  assert.strictEqual(calls, 2, 'должна быть вторая попытка');
  assert.strictEqual(r.text, src, 'исходник остаётся');
  assert.deepStrictEqual(r.left.map((h) => h.match), ['Автоматика']);
});

test('перепись: замену с новым разговорным оборотом не принимает', async () => {
  const src = 'Логика судов проста – налоговый орган прав.';
  const r = await fixRegister(src, async () => '1) Все просто: налоговый орган прав.');
  assert.strictEqual(r.text, src);
  assert.strictEqual(r.fixed, 0);
});

test('перепись: модель недоступна — текст цел, отчёт честный', async () => {
  const r = await fixRegister(TEXT, async () => { throw new Error('429'); });
  assert.strictEqual(r.text, TEXT);
  assert.strictEqual(r.left.length, 2);
});

test('перепись: чистый текст модель не трогает вовсе', async () => {
  let called = false;
  const clean = 'Инкассовое поручение направляется в банк [2].';
  const r = await fixRegister(clean, async () => { called = true; return ''; });
  assert.strictEqual(called, false);
  assert.strictEqual(r.text, clean);
  assert.strictEqual(r.found, 0);
});
