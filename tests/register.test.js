test('перепись: эмфатический повтор удаляется, текст вокруг цел', async () => {
  const src = 'Сальдо возвращается по заявлению в личном кабинете [4]. '
    + 'При этом никаких заявлений «прошу вернуть переплату» писать не нужно. '
    + 'Срок возврата — один месяц.';
  let seen = '';
  const r = await fixRegister(src, async (m) => { seen = m[1].content; return '1) —'; });
  assert.ok(seen.includes('можно удалить'), 'модели сказано, что можно удалить');
  assert.ok(seen.includes('предыдущее предложение: «Сальдо возвращается'), 'и показан контекст');
  assert.strictEqual(r.text, 'Сальдо возвращается по заявлению в личном кабинете [4]. Срок возврата — один месяц.');
  assert.deepStrictEqual(r.changes, [{ before: 'При этом никаких заявлений «прошу вернуть переплату» писать не нужно.', after: '' }]);
});

