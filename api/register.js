/**
 * Найти разговорные обороты.
 *
 * @returns {Array<{kind, hint, match, index}>} по порядку в тексте
 */
function findColloquial(text) {
  const src = String(text || '');
  const hits = [];
  for (const rule of RULES) {
    rule.re.lastIndex = 0;
    let m;
    while ((m = rule.re.exec(src)) !== null) {
      // Для подводки «Вот» и восклицания матч включает соседей —
      // в отчёт кладём только суть.
      const match = m[0].replace(/^[.!?…\s]+/, '').trim();
      const index = m.index + (m[0].length - m[0].replace(/^[.!?…\s]+/, '').length);
      hits.push({ kind: rule.kind, hint: rule.hint, match, index });
      if (m[0].length === 0) rule.re.lastIndex += 1;
    }
  }
  // Короткое правило («тут») не должно дублировать длинное («тут же»).
  hits.sort((a, b) => a.index - b.index || b.match.length - a.match.length);
  return hits.filter((h, i, all) => !all.slice(0, i).some(
    (p) => h.index >= p.index && h.index < p.index + p.match.length));
}

/** Плотность на 1000 знаков — для замеров и сравнения с корпусом. */
function colloquialRate(text) {
  const len = String(text || '').replace(/\s/g, '').length;
  if (!len) return 0;
  return (findColloquial(text).length / len) * 1000;
}

/**
 * Предложения, в которых есть находки, — с их границами в тексте.
 * Делим так же, как перепись: точка в «ст. 15» конец фразы не означает.
 */
function offendingSentences(text) {
  const src = String(text || '');
  const hits = findColloquial(src);
  if (!hits.length) return [];

  const { splitSentences } = require('./polish');
  const out = [];
  let from = 0;
  for (const sentence of splitSentences(src)) {
    const at = src.indexOf(sentence, from);
    if (at < 0) continue;
    from = at + sentence.length;
    const own = hits.filter((h) => h.index >= at && h.index < at + sentence.length);
    if (own.length) out.push({ sentence, at, hits: own });
  }
  return out;
}

const FIX_TASK = 'Ниже предложения из научной работы (курсовой). В каждом есть '
  + 'разговорный оборот, идиома, жаргон или риторическая подводка — в '
  + 'академическом тексте они недопустимы. Перепиши каждое предложение '
  + 'научным языком.\n'
  + 'Сохрани смысл полностью: все нормы, номера статей и актов, даты, '
  + 'суммы, названия, ссылки в квадратных скобках вида [3] — дословно.\n'
  + 'Не добавляй новых фактов. Не сокращай мысль. Канцелярит тоже не '
  + 'нужен: без «является», «осуществляется», «в рамках».\n'
  + 'Ответ — строго в том же формате и с теми же номерами: «1) …», '
  + '«2) …», по одному предложению на строку, без пояснений.\n\n'
  + 'Образец.\n'
  + 'Было: Логика судов проста – налоговый орган действует в пределах полномочий.\n'
  + 'Стало: Логика судов состоит в следующем: налоговый орган действует в пределах полномочий.\n'
  + 'Было: Законодателю стоило бы установить жесткий срок для такой замены.\n'
  + 'Стало: Законодателю целесообразно установить жесткий срок для такой замены.';

/** Разобрать ответ «1) …\n2) …» в словарь номер → текст. */
function parseNumbered(answer) {
  const out = {};
  const re = /^\s*(\d+)[).]\s*(.+?)\s*$/gm;
  let m;
  while ((m = re.exec(String(answer || ''))) !== null) out[Number(m[1])] = m[2];
  return out;
}

/**
 * Заменить разговорные обороты в тексте.
 *
 * Модель переписывает только предложения с находками — не весь раздел:
 * перепись целиком сдвигает ритм и теряет фактуру, а здесь задача
 * точечная. Каждую замену проверяем: оборот ушёл, нормы и ссылки [N]
 * на месте, объём не усох больше чем на треть. Не прошла — с одной
 * второй попыткой; не прошла и она — оставляем исходное предложение и
 * сообщаем, что осталось (честный отчёт лучше молча испорченной нормы).
 *
 * @param {string} text
 * @param {function} ask (messages) => Promise<string>
 * @returns {Promise<{text, found, fixed, left: Array<{match, kind}>, changes: Array<{before, after}>}>}
 */
async function fixRegister(text, ask) {
  const { lostFacts, lostRefs } = require('./facts');
  let src = String(text || '');
  const initial = offendingSentences(src);
  const found = initial.reduce((n, o) => n + o.hits.length, 0);
  if (!initial.length || typeof ask !== 'function') {
    return { text: src, found, fixed: 0, left: initial.flatMap((o) => o.hits), changes: [] };
  }

  const accept = (before, after) => after
    && !findColloquial(after).length
    && !lostFacts(before, after).length
    && !lostRefs(before, after).length
    && after.length >= before.length * 0.66;

  const changes = [];
  let pending = initial;
  for (let attempt = 1; attempt <= 2 && pending.length; attempt += 1) {
    const list = pending.map((o, i) => {
      const hints = o.hits.map((h) => `«${h.match}» → ${h.hint}`).join('; ');
      return `${i + 1}) ${o.sentence}\n   (заменить: ${hints})`;
    }).join('\n');

    let answer = '';
    try {
      answer = await ask([
        { role: 'system', content: FIX_TASK },
        { role: 'user', content: list },
      ]);
    } catch (e) {
      break;   // модель недоступна — отдаём как есть, с отчётом
    }

    const got = parseNumbered(answer);
    const still = [];
    pending.forEach((o, i) => {
      const repl = (got[i + 1] || '').replace(/^«|»$/g, '').trim();
      if (accept(o.sentence, repl) && src.includes(o.sentence)) {
        src = src.replace(o.sentence, repl);
        changes.push({ before: o.sentence, after: repl });
      } else {
        still.push(o);
      }
    });
    pending = still;
  }

  const left = findColloquial(src).map((h) => ({ match: h.match, kind: h.kind }));
  return { text: src, found, fixed: Math.max(0, found - left.length), left, changes };
}

module.exports = { RULES, findColloquial, colloquialRate, offendingSentences, parseNumbered, fixRegister };
