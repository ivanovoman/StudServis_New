/**
 * Сторож научного стиля: разговорные обороты в академическом тексте.
 *
 * Откуда взялся. Заказчик прочёл работу по взысканию налоговой
 * задолженности и выписал обороты, которые в курсовой недопустимы:
 *
 *   «Проблема здесь одна, но системная»          → риторическая подводка
 *   «если на счету пусто»                         → разговорное
 *   «Логика судов проста»                         → разговорная оценка
 *   «как снежный ком»                             → образное выражение
 *   «Отдельная головная боль»                     → фразеологизм
 *   «инкассо может быть направлено»               → профессиональный жаргон
 *   «автоматика ФНС видит…»                       → жаргон + олицетворение
 *   «законодателю стоило бы установить»           → разговорная модальность
 *
 * Причина была не в модели, а в задании: основной промпт просил писать
 * «в стиле юридического блога», разрешал «разговорные связки» и прямо
 * противопоставлял себя «статье для журнала ВАК». Промпт поправлен, но
 * одного запрета мало — это проверено пять раз на других дефектах.
 * Поэтому здесь код: находит такие обороты, а перепись (fixRegister)
 * заменяет предложения, где они стоят, и проверяет результат.
 *
 * Живость при этом не запрещена — заказчик её сознательно разрешил.
 * Живость — это ритм, прямая оценка, пример после тезиса. Разговорная
 * лексика, идиомы и жаргон к живости не относятся: это смена регистра,
 * и научный руководитель её отметит.
 *
 * Что автор сам пишет в академических работах, сюда не входит, даже
 * если звучит не вполне книжно: «юрлицо» (14 раз), «бизнес» (18),
 * «зарплата» (2). Это решение заказчика, а не сторожа.
 *
 * Калибровка — по корпусу автора (tests/register.test.js и замер в
 * КАРТА_И_РАЗРЫВЫ.md): в четырёх академических работах Коколова сторож
 * обязан молчать. Правило, срабатывающее на академическом тексте
 * автора, — ложное, его здесь быть не должно.
 */

