/**
 * Извлечение фактуры из юридического текста.
 *
 * Зачем отдельный модуль. Проверка «не потерялись ли при переписи
 * ссылки на нормы» нужна сразу в нескольких местах: в сторожа
 * конвейера переписи, в сведении черновиков от разных моделей, в
 * будущей проверке готовой работы. Пока регулярки жили копиями в
 * инструментах, они разошлись и в каждой копии был один и тот же
 * изъян.
 *
 * Изъян был такой: ловилось только сокращение «ст. 15», а написанное
 * словом «статья 15 Конституции» не ловилось вовсе. Опыт показал цену
 * ошибки — в разделе, где модель расставила четыре ссылки словами,
 * сторож насчитал ноль фактуры и спокойно пропустил бы её потерю.
 *
 * Отсюда второе требование: приводить к одному виду. При переписи
 * модель свободно меняет «ст. 105» на «статьей 105» — это та же
 * норма, и гонять перепись на бис из-за смены падежа не нужно.
 * Поэтому всё сводится к виду «ст. 105».
 */

'use strict';

// Единицы текста нормы: и сокращением, и словом, во всех падежах.
const UNITS = [
  { key: 'ст', words: 'стать(?:я|и|е|ю|ёй|ей)', short: 'ст' },
  { key: 'п', words: 'пункт(?:а|у|ом|е|ы|ов)?', short: 'п' },
  { key: 'ч', words: 'част(?:ь|и|ью|ей)', short: 'ч' },
  { key: 'абз', words: 'абзац(?:а|у|ем|е)?', short: 'абз' },
  { key: 'гл', words: 'глав(?:а|ы|е|у|ой)', short: 'гл' },
];

const UNIT_RE = new RegExp(
  '(?:' + UNITS.map((u) => `${u.key}\\.|${u.words}`).join('|') + ')'
  + '\\s*(\\d+(?:\\.\\d+)?)',
  'gi'
);

// Кодексы и Конституция — ловим, чтобы отличить ст. 15 ГК от ст. 15 УК.
//
// Граница слова \b здесь не годится: в JavaScript она считается по
// латинице, цифрам и подчёркиванию, а перед кириллической «У» в «УК
// РФ» границы не возникает — выражение молча не находит ничего. Та же
// ошибка сидела в первой копии регулярок и делала сторожа слепым к
// названиям кодексов. Поэтому край слова задан явным взглядом назад.
const CODES = /(?<![А-Яа-яЁёA-Za-z])(?:ГК|УК|ТК|КоАП|ГПК|АПК|УПК|НК|СК|ЖК|БК|ЗК)\s*РФ|Конституци(?:я|и|ей|ю)\s+(?:РФ|Российской\s+Федерации)/gi;

// Номера законов и актов: № 184-ФЗ, № 1-П, № 23.
const NUMBERS = /№\s*\d+[-–]?[А-ЯA-Zа-яa-z]*/g;

// Годы — часто это год принятия акта или издания работы.
const YEARS = /\b(?:19|20)\d{2}\b/g;

/** Приводит найденную единицу к короткой записи: «статьи 15» → «ст. 15». */
function normalizeUnit(match, number) {
  const head = match.toLowerCase();
  for (const u of UNITS) {
    if (head.startsWith(u.key + '.') || new RegExp('^' + u.words, 'i').test(head)) {
      return `${u.short}. ${number}`;
    }
  }
  return `${head} ${number}`;
}

/** Приводит название кодекса к одному виду: «Конституции РФ» → «Конституция РФ». */
function normalizeCode(raw) {
  const s = raw.replace(/\s+/g, ' ').trim();
  if (/^Конституци/i.test(s)) return 'Конституция РФ';
  return s.toUpperCase().replace(/\s+/g, ' ');
}

/**
 * Возвращает набор единиц фактуры, приведённых к одному виду.
 *
 * @param {string} text исходный текст
 * @returns {Set<string>}
 */
function extractFacts(text) {
  const out = new Set();
  if (!text) return out;

  for (const m of text.matchAll(UNIT_RE)) out.add(normalizeUnit(m[0], m[1]));
  for (const m of text.matchAll(CODES)) out.add(normalizeCode(m[0]));
  for (const m of text.matchAll(NUMBERS)) out.add(m[0].replace(/\s+/g, ' ').replace('№ ', '№'));
  for (const m of text.matchAll(YEARS)) out.add(m[0]);

  return out;
}

/**
 * Что было в исходном тексте, но пропало в переписанном.
 *
 * @param {string} before черновой кусок
 * @param {string} after переписанный кусок
 * @returns {string[]} потерянное, по-человечески перечислимое
 */
function lostFacts(before, after) {
  const was = extractFacts(before);
  const now = extractFacts(after);
  return [...was].filter((f) => !now.has(f));
}

module.exports = { extractFacts, lostFacts };
