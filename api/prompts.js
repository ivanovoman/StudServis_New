      + '  укладывается в две. Четыре и больше - недопустимо: это курсовая,\n'
      + '  а не диссертация.\n'
      + '- Выбрав число, прямо объясни в одну строку, почему именно столько.';
    rulePlan =
      'ЧИСЛО ГЛАВ - ДВЕ или ТРИ, на твоё усмотрение по теме. Если в анализе\n'
      + 'темы структура уже намечена, следуй ей. Четыре и больше глав в\n'
      + 'курсовой недопустимы: укрупняй, а не дроби.';
    frame =
      '- Рабочий каркас:\n'
      + '  при трёх главах - теория / регулирование и практика / проблемы и\n'
      + '  пути совершенствования;\n'
      + '  при двух - теория / регулирование, практика и проблемы вместе.\n'
