/**
 * Досье по разделу: подготовка материала для черновика.
 *
 * Отдельным модулем, потому что этим пользуется и сервер при сборке
 * работы, и инструменты замера. Сама добыча статей и отбор выдержек
 * живут в Python (`backend/app/modules/rag_service/dossier.py`),
 * здесь — обращение к ним и превращение ответа в задание модели.
 */

'use strict';

const PY_BACKEND = process.env.PY_BACKEND_URL || 'http://127.0.0.1:8000';

/**
 * Досье по разделу — выдержки из статей, прочитанных целиком.
 *
 * Это главный источник содержания для черновика. Опыт показал, что
 * без поданного материала модель сочиняет фактуру и делает это
 * правдоподобно: реквизиты настоящие, а привязка выдумана. С
 * поданным материалом она берёт из него почти всё и своего не
 * добавляет.
 *
 * Если глубокий разбор темы не делался, досье придёт пустым, и
 * раздел пишется как раньше — на метаданных публикаций.
 */
async function fetchDossier(ownerKey, heading, topic, budget) {
  if (!ownerKey || !heading) return null;
  try {
    const r = await fetch(`${PY_BACKEND}/api/v1/library/research/dossier`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Owner-Key': ownerKey,
      },
      body: JSON.stringify({
        heading: String(heading).slice(0, 300),
        topic: String(topic || '').slice(0, 300),
        budget_chars: Number(budget || process.env.DOSSIER_CHARS || 9000),
      }),
    });
    if (!r.ok) return null;
    const data = await r.json();
    return data && data.excerpts > 0 ? data : null;
  } catch (e) {
    console.error('Досье по разделу не собралось:', e.message);
    return null;
  }
}

/**
 * Превращает досье в системный блок задания.
 *
 * Правила написаны так, чтобы закрыть обе беды разом. Первая —
 * сочинительство: прямо сказано, что можно называть, а что нельзя.
 * Вторая — пустота черновика: следом за черновиком идёт перепись
 * кусками, а она меняет форму, но не добавляет знания. Чего нет в
 * черновике, того не будет и в готовой работе, поэтому от модели
 * требуется использовать поданный материал, а не упомянуть его.
 */
function dossierBlock(dossier) {
  if (!dossier || !dossier.prompt_block) return '';

  // Список норм приходит уже очищенным: годы и номера сносок из него
  // выброшены на стороне Python, там же, где собиралось досье.
  const norms = dossier.norms || [];

  return 'МАТЕРИАЛ ДЛЯ ЭТОГО РАЗДЕЛА — выдержки из статей, которые '
    + 'прочитаны целиком. Это проверенные тексты, а не пересказ по '
    + 'памяти.\n\n'
    + dossier.prompt_block
    + '\n\nКАК С ЭТИМ РАБОТАТЬ:\n'
    + '- Раздел пиши ПО ЭТИМ ВЫДЕРЖКАМ. Разбери, сопоставь, покажи, '
    + 'в чём авторы сходятся и в чём расходятся. Пересказывать подряд '
    + 'не нужно — нужно рассуждение, опирающееся на них.\n'
    + '- Ссылайся номером в квадратных скобках: [1], [2]. Ссылка '
    + 'обязательна там, где излагаешь чужую позицию, определение или '
    + 'цифру.\n'
    + (norms.length
      ? `- Нормы, которые можно называть: ${norms.join(', ')}. Это те, `
        + 'что действительно упомянуты в источниках. Любую другую '
        + 'статью, закон или постановление называть ЗАПРЕЩЕНО — если '
        + 'нужной нормы в списке нет, пиши мысль без ссылки на номер.\n'
      : '- Номера статей, законов и постановлений называть ЗАПРЕЩЕНО: '
        + 'в поданных источниках их нет, а по памяти ты ошибёшься.\n')
    + '- Фамилии учёных бери только из выдержек и из перечня выше. '
    + 'Выдуманная ссылка на несуществующую работу — грубая ошибка.\n'
    + '- Цитировать дословно можно короткими кусками и обязательно с '
    + 'номером источника. Длинных цитат не делай: работу проверяют на '
    + 'заимствования.\n'
    + '- Чем плотнее раздел набит содержанием из выдержек, тем лучше. '
    + 'Общие слова («данный вопрос является актуальным») место '
    + 'занимают, а смысла не несут.\n'
    + '- Выдержки — это материал для развёртывания, а не для пересказа '
    + 'покороче. Каждую взятую мысль поясни: что именно утверждает '
    + 'автор, из чего он исходит, к чему это ведёт на практике. '
    + 'Заданный объём раздела выдержи полностью — коротким пересказом '
    + 'источников он не заменяется.\n'
    + '- Задействуй все поданные источники, а не один-два удобных. '
    + 'Если авторы расходятся во мнениях, покажи это расхождение: '
    + 'именно оно делает раздел научным, а не справочным.';
}

module.exports = { fetchDossier, dossierBlock };
