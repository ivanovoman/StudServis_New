/**
 * Перепись черновика кусками: из машинного текста в авторскую манеру.
 *
 * Второе звено конвейера. Первое (досье из прочитанных статей) даёт
 * черновику содержание, это — форму. Разделение не случайное: опыт
 * показал, что на коротком куске модель держит ритм, а на целом
 * разделе выравнивает все фразы под одну длину, и текст становится
 * машинным. Отсюда куски по 350-500 знаков.
 *
 * Дорого достались три вещи, и каждая здесь закреплена кодом, а не
 * просьбой в задании:
 *
 * 1. Нарезка по границам предложений. Точка в «ст. 15» предложение
 *    не кончает — на юридическом тексте это главный источник ложных
 *    разрывов.
 *
 * 2. Сторож фактуры. При переписи молча пропадают ссылки на нормы:
 *    текст остаётся гладким, а рассуждение остаётся без статьи, на
 *    которую опиралось. Слова «ничего не выбрасывай» в задании от
 *    этого не спасают.
 *
 * 3. Сторож объёма. Перепись ужимает текст на пятую часть, и раздел
 *    на 5500 знаков превращается в 4500. «Объём примерно тот же» в
 *    задании тоже не работает — нужны точные числа в лицо.
 */

'use strict';

const { lostFacts, lostRefs } = require('./facts.js');

// Границы куска. Меньше — рвётся мысль, больше — модель начинает
// выравнивать фразы под одну длину.
const MIN_PIECE = 350;
const MAX_PIECE = 500;

// Доля исходного объёма, ниже которой кусок считается усохшим.
const KEEP_SHARE = 0.9;

// Нижняя граница доли коротких фраз.
//
// Цель здесь пришлось пересматривать дважды. Сперва ориентиром были
// статьи автора: коротких фраз треть, медиана 11 слов. Потом
// заказчик прислал его курсовые и магистерскую, и оказалось, что в
// научных работах он пишет совершенно иначе — медиана 17 слов,
// коротких 17,6 %, длинных 26,9 % против 8,3 % в статьях.
//
// Курсовую надо писать в научной ноте, но заказчик прямо просил не
// превращать её в канцелярит. Поэтому ориентир — смесь двух
// корпусов: медиана 13, коротких около четверти, длинных каждая
// шестая.
//
// Сам порог — не цель, а защита от крайности: он ловит куски, где
// коротких фраз нет совсем. Требовать точную долю на куске в
// четыре-пять фраз бессмысленно, а попытка это сделать однажды уже
// дала рубленый текст с медианой 9 слов.
const SHORT_SHARE = 0.15;
const SHORT_WORDS = 8;

// Куски короче этого на ритм не проверяем: в двух фразах доля
// коротких — величина случайная.
//
// Порог был четыре и пропустил ровно тот случай, ради которого
// заведён. Когда правила подтолкнули модель к длинным фразам, кусок
// в пятьсот знаков стал вмещать всего три предложения — и сторож
// умолк именно там, где текст сделался монотонно-длинным: ни одной
// короткой фразы на весь раздел, а предупреждений ноль. Сторож,
// отключающийся от той самой беды, которую стережёт, бесполезен.
const RHYTHM_MIN_SENTENCES = 3;

// Сколько переписанного текста показывать как левый край окна и
// сколько чернового — как правый. Окно нужно, чтобы куски стыковались
// без повторов и без «итак» в начале каждого.
const WINDOW_BEHIND = 400;
const WINDOW_AHEAD = 250;

const TASK = 'Перепиши фрагмент научной работы в манере автора.\n\n'
  + 'ЖЁСТКИЕ ПРАВИЛА:\n'
  + '- Содержание не меняй: ни одного нового факта, ни одной новой '
  + 'ссылки на норму. Ничего не выбрасывай.\n'
  + '- Объём примерно тот же.\n'
  + '- Не добавляй вступлений и выводов, не пиши «итак» и «таким '
  + 'образом» в начале.\n'
  + '- В ответе только переписанный фрагмент, без пояснений.';

const GUARD = '\u0000';

/**
 * Прячет точки, которые предложение не кончают.
 *
 * Таких три вида, и каждый в юридическом тексте встречается на
 * каждой странице:
 *
 *   - сокращения: «ст. 15», «п. 2», «с. 204»;
 *   - десятичные числа: «1.5 раза»;
 *   - инициалы: «В.Н. Кудрявцев».
 *
 * Инициалы добавились позже других и дорого обошлись. Из-за них
 * сторож ритма видел в разделе 89 предложений вместо 57 и считал
 * обрывки «В.», «Н.» короткими фразами: доля коротких выходила 45 %
 * при настоящих 17 %. Та же ошибка рвала текст на куски прямо по
 * фамилии автора, которого цитируют.
 */
function guardDots(text) {
  const abbr = /(?<![А-Яа-яЁёA-Za-z])(ст|стт|п|пп|ч|абз|гл|разд|подп|г|гг|в|вв|руб|коп|тыс|млн|млрд|см|ср|напр|рис|табл|стр|с|изд|им|др|пр|т|е|д)\./gi;
  // Инициал — одиночная заглавная буква с точкой.
  const initials = /(?<![А-Яа-яЁёA-Za-z])([А-ЯЁA-Z])\./g;
  return String(text || '')
    .replace(abbr, (m) => m.replace('.', GUARD))
    .replace(initials, (m, letter) => `${letter}${GUARD}`)
    .replace(/(\d)\.(\d)/g, `$1${GUARD}$2`);
}

/**
 * Делит текст на предложения.
 *
 * Граница — точка, за которой идёт пробел и заглавная буква или
 * цифра. Требование заглавной важно: без него «и т. д. далее по
 * тексту» разрывается посередине. Переносы строк — тоже границы:
 * абзац отдельной мыслью считается всегда.
 *
 * Эта же мера используется и при нарезке на куски, и при подсчёте
 * ритма. Когда они расходились, сторож ритма видел в разделе 82
 * предложения там, где замер стиля насчитывал 53, и гнал перепись
 * из-за выдуманного недобора коротких фраз.
 */
function splitSentences(text) {
  return guardDots(text)
    .split(/\n+/)
    .flatMap((para) => para.split(/(?<=[.!?…])[ \t]+(?=[«"'(\[]?[А-ЯЁA-Z0-9•])/))
    .map((s) => s.replace(new RegExp(GUARD, 'g'), '.').trim())
    .filter(Boolean);
}

/**
 * Нарезка текста на куски по границам предложений.
 *
 * Резать по счётчику знаков нельзя: граница попадёт в середину фразы,
 * и переписывать придётся обрубок. Набираем целые предложения, пока
 * кусок не дорастёт до нижней границы.
 */
function splitPieces(text, min = MIN_PIECE, max = MAX_PIECE) {
  const sentences = splitSentences(text);

  const pieces = [];
  let buf = '';
  for (const s of sentences) {
    const next = buf ? `${buf} ${s}` : s;
    // Фразу не рвём: если кусок набрал нижнюю границу, а следующее
    // предложение выводит за верхнюю — закрываем кусок.
    if (buf.length >= min && next.length > max) {
      pieces.push(buf);
      buf = s;
    } else {
      buf = next;
    }
  }
  if (buf) pieces.push(buf);
  return pieces;
}

/**
 * Доля коротких фраз в тексте.
 *
 * Предложения считаются так же, как при нарезке: точка в «ст. 15»
 * конец фразы не означает.
 */
function shortShare(text) {
  const sentences = splitSentences(text);

  if (!sentences.length) return { share: 1, sentences: 0, short: 0 };
  const short = sentences
    .filter((s) => s.split(/\s+/).filter(Boolean).length <= SHORT_WORDS).length;
  return { share: short / sentences.length, sentences: sentences.length, short };
}

/** Правила авторской манеры с образцами. */
function styleRules(samples) {
  const list = Array.isArray(samples) ? samples : [];
  return 'КАК ПИШЕТ АВТОР, В ЧЬЕЙ МАНЕРЕ НУЖНО ПЕРЕПИСАТЬ\n\n'
    + 'Это научная работа, и писать надо научным языком — но живым, '
    + 'а не канцелярским.\n'
    + 'Предложения РАЗНОЙ длины — это главное. Основная масса фраз '
    + 'средние, двенадцать-восемнадцать слов. Примерно каждая '
    + 'четвёртая короткая, пять-восемь слов. И примерно каждая '
    + 'шестая — длинная, в двадцать пять слов и больше: в научном '
    + 'тексте развёрнутая мысль с придаточными уместна и нужна.\n'
    + 'Ровный текст машинный. Но и рубленые короткие фразы подряд '
    + 'тоже машинные — не дроби мысль там, где она требует развития.\n'
    + 'Пояснение в скобках — заметная примета этого автора: в его '
    + 'работах оно встречается раз на девятьсот знаков. Скобками он '
    + 'вводит сокращение («Гражданский кодекс Российской Федерации '
    + '(далее — ГК РФ)»), уточняет норму, оговаривает условие. '
    + 'Вставь такие пояснения там, где они и правда уточняют мысль; '
    + 'пустых скобок ради приметы не ставь.\n'
    + 'Канцелярит под запретом: «является», «осуществляется», '
    + '«в целях», «в рамках», «данный» в значении «этот».\n'
    + 'Прямая оценка вместо уклончивости.\n\n'
    + list.map((s, i) => `ОТРЫВОК ${i + 1}\n${s}`).join('\n\n');
}

/**
 * Переписывает черновик кусками.
 *
 * @param {string} draft черновой текст
 * @param {object} opts
 * @param {function} opts.ask вызов модели: (messages) => Promise<string>
 * @param {string} opts.style блок с авторской манерой
 * @param {function} [opts.onPiece] сообщает о ходе работы
 * @returns {Promise<{text, pieces, retries, fallbacks, shortfalls, lost}>}
 */
async function polishDraft(draft, opts) {
  const { ask, style = '', onPiece = null } = opts || {};
  if (typeof ask !== 'function') throw new Error('polishDraft: нужен ask');

  const pieces = splitPieces(draft);
  const done = [];
  let retries = 0;
  let fallbacks = 0;
  let shortfalls = 0;
  let flats = 0;

  for (let i = 0; i < pieces.length; i += 1) {
    const piece = pieces[i];

    // Окно: хвост уже переписанного и начало следующего чернового.
    // Без него куски стыкуются плохо — модель начинает каждый заново.
    const behind = done.join(' ').slice(-WINDOW_BEHIND);
    const ahead = (pieces[i + 1] || '').slice(0, WINDOW_AHEAD);

    const context = [
      behind ? `УЖЕ ПЕРЕПИСАНО ВЫШЕ (не повторяй, продолжай связно):\n${behind}` : '',
      ahead ? `ДАЛЬШЕ В ЧЕРНОВИКЕ (не переписывай, только для связности):\n${ahead}` : '',
    ].filter(Boolean).join('\n\n');

    const base = `${TASK}${context ? `\n\n${context}` : ''}`
      + `\n\nФРАГМЕНТ ДЛЯ ПЕРЕПИСИ:\n${piece}`;

    let text = await ask([
      { role: 'system', content: style },
      { role: 'user', content: base },
    ]);

    // Сторож следит за тремя вещами: фактура, ссылки на источники,
    // объём. Ссылки добавились после замера всего конвейера: из
    // девятнадцати пропало три, и раздел местами стал пересказом без
    // опоры на литературу.
    let lost = lostFacts(piece, text);
    let dropped = lostRefs(piece, text);
    let short = text.length < piece.length * KEEP_SHARE;

    // Ритм: у автора почти каждая третья фраза короткая, а перепись
    // сама по себе до этого не дотягивает.
    let rhythm = shortShare(text);
    let flat = rhythm.sentences >= RHYTHM_MIN_SENTENCES
      && rhythm.share < SHORT_SHARE;

    if (lost.length || dropped.length || short || flat) {
      retries += 1;
      const claims = [];
      if (lost.length) {
        claims.push(`ОБЯЗАТЕЛЬНО сохрани в тексте: ${lost.join(', ')}. `
          + 'В прошлый раз ты это потерял.');
      }
      if (dropped.length) {
        claims.push('ОБЯЗАТЕЛЬНО сохрани ссылки на источники: '
          + `${dropped.map((r) => `[${r}]`).join(', ')}. Они указывают, `
          + 'откуда взята мысль, и выбрасывать их нельзя.');
      }
      if (short) {
        claims.push(`Объём: в исходном фрагменте ${piece.length} знаков, `
          + `в твоём прошлом ответе ${text.length}. Нужно не меньше `
          + `${Math.round(piece.length * KEEP_SHARE)} знаков — разверни `
          + 'мысль подробнее, но ничего не придумывай сверх сказанного.');
      }
      if (flat) {
        const нужно = Math.ceil(rhythm.sentences * SHORT_SHARE);
        claims.push(`Ритм: в твоём прошлом ответе ${rhythm.sentences} `
          + `предложений, коротких (до ${SHORT_WORDS} слов) всего `
          + `${rhythm.short}. Нужно минимум ${нужно}. Разбей длинные `
          + 'фразы на части — короткая фраза после длинной держит '
          + 'внимание, а ровный текст читается как машинный.');
      }

      const second = await ask([
        { role: 'system', content: style },
        { role: 'user', content: `${TASK}\n\n${claims.join('\n')}`
          + `\n\nФРАГМЕНТ ДЛЯ ПЕРЕПИСИ:\n${piece}` },
      ]);

      // Вторую попытку берём, только если она не хуже: бывает, что
      // исправив объём, модель роняет ссылку.
      const secondLost = lostFacts(piece, second);
      const secondDropped = lostRefs(piece, second);
      if (secondLost.length + secondDropped.length
          <= lost.length + dropped.length) {
        text = second;
        lost = secondLost;
        dropped = secondDropped;
        short = text.length < piece.length * KEEP_SHARE;
        rhythm = shortShare(text);
        flat = rhythm.sentences >= RHYTHM_MIN_SENTENCES
          && rhythm.share < SHORT_SHARE;
      }
    }

    if (lost.length || dropped.length) {
      // Фактуру вернуть не удалось — берём черновой кусок. Корявая
      // фраза лучше пропавшей ссылки на закон.
      fallbacks += 1;
      text = piece;
    } else {
      if (short) shortfalls += 1;
      if (flat) flats += 1;
    }

    done.push(text);
    if (onPiece) onPiece(i + 1, pieces.length);
  }

  const result = done.join('\n\n');
  return {
    text: result,
    pieces: pieces.length,
    retries,
    fallbacks,
    shortfalls,
    flats,
    lost: lostFacts(draft, result),
    shortShare: shortShare(result).share,
    droppedRefs: lostRefs(draft, result),
  };
}

module.exports = {
  MIN_PIECE,
  MAX_PIECE,
  KEEP_SHARE,
  SHORT_SHARE,
  shortShare,
  splitSentences,
  TASK,
  splitPieces,
  styleRules,
  polishDraft,
};
