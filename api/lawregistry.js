/**
 * Упоминания номера закона: «№ 102-ФЗ», «N 102-ФЗ», «102-ФЗ», «ФЗ-102»,
 * «ФЗ № 102», «№ 2300-1», «№ 1-ФКЗ». Номер приводим к виду «102-ФЗ».
 */
const NUM_RE = /(?:(?:№|N)\s*(\d{1,4})-(ФКЗ|ФЗ|1)(?![А-Яа-яЁё\d])|(?<![\d.])(\d{1,4})-(ФКЗ|ФЗ)(?![А-Яа-яЁё])|ФЗ\s*-\s*(\d{1,4})(?!\d)|ФЗ\s*№\s*(\d{1,4})(?![\d-]))/g;
const DATE_RE = /от\s+(\d{1,2})\.(\d{1,2})\.(\d{4})/g;

function numMentions(text) {
  const out = [];
  let m;
  NUM_RE.lastIndex = 0;
  while ((m = NUM_RE.exec(text))) {
    let num;
    if (m[1]) num = `${m[1]}-${m[2]}`;
    else if (m[3]) num = `${m[3]}-${m[4]}`;
    else num = `${m[5] || m[6]}-ФЗ`;
    out.push({ num, start: m.index, end: m.index + m[0].length, raw: m[0] });
  }
  return out;
}

function dateMentions(text) {
  const out = [];
  let m;
  DATE_RE.lastIndex = 0;
  while ((m = DATE_RE.exec(text))) {
    const date = `${m[1].padStart(2, '0')}.${m[2].padStart(2, '0')}.${m[3]}`;
    out.push({ date, start: m.index, end: m.index + m[0].length });
  }
  return out;
}

/** Есть ли между двумя позициями граница, через которую реквизит не тянется. */
function separated(text, a, b) {
  const between = text.slice(Math.min(a, b), Math.max(a, b));
  // Точка с запятой, перевод строки, конец предложения или другое
  // название в кавычках — уже другой акт.
  return /[;\n]|\.\s+[А-ЯЁ]|[»"]\s*[,и]\s*[«"]/.test(between);
}

const MAX_GAP = 70;

/**
 * Найти расхождения.
 * @returns {Array<{label: string, status: 'mismatch', note: string,
 *                  expected: string, found: string}>}
 */
function checkLawNames(text) {
  const src = String(text || '');
  if (!src) return [];
  const nums = numMentions(src);
  const dates = dateMentions(src);
  const problems = [];
  const seen = new Set();

  for (const law of LAWS) {
    law.rx.lastIndex = 0;
    let m;
    while ((m = law.rx.exec(src))) {
      const tStart = m.index;
      const tEnd = m.index + m[0].length;
      // Ближайший номер в той же части фразы.
      let best = null;
      for (const n of nums) {
        let between;
        if (n.end <= tStart) {
          // Номер перед названием: «№ 102-ФЗ „Об ипотеке…“». Запятая
          // между ними — перечень: «№ 214-ФЗ, ГПК РФ, ФЗ „Об исполнительном
          // производстве“» — номер относится к другому акту.
          between = src.slice(n.end, tStart);
        } else if (n.start >= tEnd) {
          // Номер после названия: сначала пропускаем хвост названия до
          // закрывающей кавычки — в нём бывают запятые («О цифровых
          // финансовых активах, цифровой валюте…»).
          between = src.slice(tEnd, n.start);
          const q = between.search(/[»"]/);
          if (q >= 0 && !/[;\n]/.test(between.slice(0, q))) between = between.slice(q + 1);
        } else {
          between = '';
        }
        if (between.length > MAX_GAP) continue;
        if (/,/.test(between.replace(/«[^»]*»/g, ''))) continue;
        if (separated(src, n.end <= tStart ? n.end : tEnd, n.end <= tStart ? tStart : n.start)) continue;
        const gap = between.length;
        if (!best || gap < best.gap) best = { ...n, gap };
      }
      if (!best) continue;

      // Под этим названием может быть несколько законов с разными
      // номерами — сверяем со всеми, у кого совпадает название.
      const same = LAWS.filter((l) => {
        l.rx.lastIndex = 0;
        return l.rx.test(m[0]);
      });
      law.rx.lastIndex = tEnd;
      const ok = same.find((l) => l.num === best.num);
      // Подпись — от номера до конца названия, с закрывающей кавычкой.
      let to = Math.max(best.end, tEnd);
      const close = src.slice(to, to + 160).search(/[»"]/);
      if (close >= 0 && !/[;\n]/.test(src.slice(to, to + close))) to += close + 1;
      const label = src.slice(Math.min(best.start, tStart), to).replace(/\s+/g, ' ').trim();
      if (!ok) {
        const key = `n:${law.num}:${best.num}`;
        if (seen.has(key)) continue;
        seen.add(key);
        problems.push({
          label, status: 'mismatch', expected: `№ ${law.num} от ${law.date}`, found: best.num,
          note: `закон «${law.title}» — № ${law.num} от ${law.date}, а указан ${best.num}. Проверьте реквизиты`,
        });
        continue;
      }
      // Номер верный — проверяем дату, если она стоит вплотную к номеру.
      const d = dates.find((x) => (Math.abs(x.end - best.start) <= 3 || Math.abs(best.end - x.start) <= 3));
      if (d && d.date !== ok.date) {
        const key = `d:${ok.num}:${d.date}`;
        if (seen.has(key)) continue;
        seen.add(key);
        problems.push({
          label: src.slice(Math.min(d.start, best.start), Math.max(d.end, best.end)).trim(),
          status: 'mismatch', expected: `от ${ok.date}`, found: d.date,
          note: `закон № ${ok.num} «${ok.title}» принят ${ok.date}, а указано ${d.date}`,
        });
      }
    }
  }
  return problems;
}

