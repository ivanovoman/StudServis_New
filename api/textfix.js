/**
 * Починка слов, где кириллица перемешана с латиницей.
 *
 * Модель изредка сбивается и выдаёт «kompetенции», «dispositивного»,
 * «extraterриториальными» — начало слова латиницей, хвост кириллицей.
 * В готовой работе это выглядит как брак, и заметить такое глазами
 * трудно: буквы визуально почти не отличаются.
 *
 * Раньше похожая порча шла из промпта (в роли модели стояло
 * «Красный octябрь»), и после правки промпта пропала. Эти пять слов на
 * двадцать девять тысяч знаков — уже не промпт, а сама модель, так что
 * лечить приходится после генерации.
 *
 * Замена идёт по таблице транслитерации и только внутри смешанных слов.
 * Целиком латинские термины (lex specialis, GDPR, ex nunc) не трогаются
 * вообще — в юридическом тексте они законны и нужны.
 *
 * Исправление не молчаливое: список заменённых слов возвращается
 * наружу, чтобы показать его пользователю. Транслитерация угадывает не
 * всегда — «виндicatorийский» она превратит в «виндисаторийский», хотя
 * автор имел в виду «виндикационный». Пусть человек увидит и поправит.
 */

'use strict';

/** Латинская буква → кириллическая. */
const MAP = {
  a: 'а', b: 'б', c: 'с', d: 'д', e: 'е', f: 'ф', g: 'г', h: 'х',
  i: 'и', j: 'й', k: 'к', l: 'л', m: 'м', n: 'н', o: 'о', p: 'п',
  q: 'к', r: 'р', s: 'с', t: 'т', u: 'у', v: 'в', w: 'в', x: 'х',
  y: 'у', z: 'з',
  A: 'А', B: 'Б', C: 'С', D: 'Д', E: 'Е', F: 'Ф', G: 'Г', H: 'Х',
  I: 'И', J: 'Й', K: 'К', L: 'Л', M: 'М', N: 'Н', O: 'О', P: 'П',
  Q: 'К', R: 'Р', S: 'С', T: 'Т', U: 'У', V: 'В', W: 'В', X: 'Х',
  Y: 'У', Z: 'З',
};

/** Пары латинских букв с устойчивым русским чтением.
 *
 * Разбираются до одиночных букв: «x» сама по себе читается как «кс»
 * («экстра», не «ехтра»), а в паре «ex» в начале слова — тем более.
 * Без этого «extraterриториальными» чинилось в «ехтратерриториальными».
 */
const DIGRAPHS = [
  // Приставка ex- в начале слова: «экстра», а не «екстра».
  [/^ex/, 'экс'], [/^Ex/, 'Экс'], [/^EX/, 'ЭКС'],
  [/ch/g, 'ч'], [/sh/g, 'ш'], [/ph/g, 'ф'], [/th/g, 'т'],
  [/yu/g, 'ю'], [/ya/g, 'я'], [/yo/g, 'ё'], [/zh/g, 'ж'],
  [/ts/g, 'ц'], [/kh/g, 'х'], [/x/g, 'кс'], [/CH/g, 'Ч'],
  [/SH/g, 'Ш'], [/X/g, 'КС'],
];

/** Слово, в котором есть и кириллица, и латиница одновременно. */
const HYBRID_RE = /\b(?=\w*[а-яёА-ЯЁ])(?=\w*[a-zA-Z])\w+\b/g;

/**
 * Починить смешанные слова в тексте.
 *
 * @param {string} text
 * @returns {{text: string, fixed: Array<{from: string, to: string}>}}
 */
function fixHybrids(text) {
  const fixed = [];

  const out = String(text || '').replace(HYBRID_RE, (word) => {
    let repaired = word;
    for (const [re, sub] of DIGRAPHS) repaired = repaired.replace(re, sub);
    repaired = repaired.replace(/[a-zA-Z]/g, (ch) => MAP[ch] || ch);
    if (repaired !== word) fixed.push({ from: word, to: repaired });
    return repaired;
  });

  return { text: out, fixed };
}

module.exports = { fixHybrids };
