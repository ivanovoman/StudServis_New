"""Замер качества поиска по юридическим абзацам.

Нужен, чтобы решение о векторной базе принималось по цифрам, а не по
общему ощущению, что «RAG — это правильно».

Сравниваются три способа найти нужный абзац по вопросу: лексический
BM25, нейросетевые эмбеддинги и их объединение. Набор маленький
(12 абзацев, 8 запросов), но он из настоящей предметной области —
теории права, — а не из общих фраз, на которых хорошо выглядит любая
модель.

Метрики: сколько раз нужный абзац оказался первым и MRR (чем ближе к
единице, тем выше в списке стоит правильный ответ).

Запуск:  python3 tools/bench-search.py
Эмбеддинги требуют fastembed (pip install fastembed) и около 700 МБ
памяти; без него считается только BM25.
"""
import time, re
import numpy as np

DOCS = [
 ("коллизия-определение", "Юридическая коллизия представляет собой противоречие между двумя или более формально действующими нормами права, которые регулируют одно и то же общественное отношение, но предписывают взаимоисключающее поведение."),
 ("пробел", "Пробел в праве означает полное отсутствие нормы, которая регулировала бы отношение, входящее в сферу правового регулирования. При пробеле применяется аналогия закона или аналогия права."),
 ("lex-superior", "Правило lex superior derogat legi inferiori означает, что акт большей юридической силы вытесняет акт меньшей силы. Федеральный закон имеет приоритет над приказом министерства."),
 ("lex-posterior", "Правило lex posterior derogat legi priori устанавливает, что позднейший закон отменяет предшествующий, если оба имеют равную юридическую силу."),
 ("lex-specialis", "Правило lex specialis derogat legi generali означает, что специальная норма вытесняет общую норму при регулировании конкретного отношения."),
 ("ks-rf", "Конституционный Суд Российской Федерации устраняет неопределённость в вопросе о соответствии оспариваемых норм Конституции и определяет, какой из конкурирующих актов подлежит применению."),
 ("vs-rf", "Верховный Суд Российской Федерации формирует единообразную практику применения законодательства и разрешает столкновения между Гражданским кодексом и специальными законами."),
 ("переходный", "Переходный период при вступлении нового закона в силу позволяет субъектам адаптироваться к изменившимся требованиям и предотвращает блокировку гражданского оборота."),
 ("техника", "Дефекты законодательной техники возникают при бессистемном обновлении законодательства, когда новые акты принимаются без отмены устаревших, что порождает горизонтальные коллизии."),
 ("подряд", "По договору подряда подрядчик обязуется выполнить по заданию заказчика определённую работу и сдать её результат, а заказчик обязуется принять результат и оплатить его."),
 ("вертикальные", "Вертикальные коллизии возникают между нормативными актами различной юридической силы, например между федеральным законом и подзаконным нормативным актом органа исполнительной власти."),
 ("цифровизация", "Цифровизация экономики породила новые виды отношений, правовой статус участников которых — например платформенных занятых — остаётся неопределённым в действующем законодательстве."),
]
QUERIES = [
 ("что такое юридическая коллизия", "коллизия-определение"),
 ("чем коллизия отличается от пробела в праве", "пробел"),
 ("какая норма важнее: специальная или общая", "lex-specialis"),
 ("приоритет федерального закона над приказом министерства", "lex-superior"),
 ("роль Конституционного Суда в разрешении противоречий", "ks-rf"),
 ("зачем нужен переходный период при смене закона", "переходный"),
 ("почему законы противоречат друг другу, ошибки в их подготовке", "техника"),
 ("обязанности подрядчика и заказчика", "подряд"),
]
ids = [d[0] for d in DOCS]
texts = [d[1] for d in DOCS]

def score(name, rank_fn):
    t0=time.time(); hit1=0; mrr=0.0
    for q, gold in QUERIES:
        order = rank_fn(q)
        pos = order.index(gold)
        if pos==0: hit1+=1
        mrr += 1.0/(pos+1)
    dt=time.time()-t0
    print(f"{name:28} точно первым {hit1}/{len(QUERIES)}   MRR {mrr/len(QUERIES):.3f}   {dt:.2f} с")
    return mrr/len(QUERIES)

# --- BM25 ---
def tok(s): return re.findall(r'[а-яёa-z]+', s.lower())
def stem(w): return w[:6]
from collections import Counter
docs_tok=[[stem(w) for w in tok(t)] for t in texts]
df=Counter()
for d in docs_tok: df.update(set(d))
N=len(docs_tok); avgdl=sum(len(d) for d in docs_tok)/N
import math
def bm25(q):
    qs=[stem(w) for w in tok(q)]
    scores=[]
    for i,d in enumerate(docs_tok):
        tf=Counter(d); s=0.0
        for w in qs:
            if w not in tf: continue
            idf=math.log(1+(N-df[w]+0.5)/(df[w]+0.5))
            s+=idf*tf[w]*2.5/(tf[w]+1.5*(1-0.75+0.75*len(d)/avgdl))
        scores.append(s)
    return [ids[i] for i in np.argsort(-np.array(scores))]
score("BM25 (лексический)", bm25)

# --- эмбеддинги ---
from fastembed import TextEmbedding
for mname, label in [
    ("sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2","MiniLM-multilingual"),
    ("minishlab/potion-multilingual-128M","potion-multilingual"),
]:
    try:
        m=TextEmbedding(model_name=mname)
        V=np.array(list(m.embed(texts)))
        V=V/np.linalg.norm(V,axis=1,keepdims=True)
        def rank(q, m=m, V=V):
            qv=np.array(list(m.embed([q]))[0]); qv/=np.linalg.norm(qv)
            return [ids[i] for i in np.argsort(-(V@qv))]
        score(label, rank)
        # гибрид с BM25
        def hybrid(q, m=m, V=V):
            qv=np.array(list(m.embed([q]))[0]); qv/=np.linalg.norm(qv)
            dense=V@qv
            lex_order=bm25(q)
            lex={d: 1.0/(60+i) for i,d in enumerate(lex_order)}
            den_order=[ids[i] for i in np.argsort(-dense)]
            den={d: 1.0/(60+i) for i,d in enumerate(den_order)}
            total={d: lex.get(d,0)+den.get(d,0) for d in ids}
            return sorted(ids, key=lambda d:-total[d])
        score(label+" + BM25", hybrid)
    except Exception as e:
        print(f"{label}: не вышло — {e}")
