"""Профиль авторского стиля в числах.

Нужен, чтобы «пишет в стиле автора» перестало быть делом вкуса.
Скрипт снимает с текста несколько измеримых признаков и показывает,
насколько готовый раздел приблизился к образцу.

Признаки выбраны не наугад: это то, чем публицистика практикующего
юриста отличается от машинного академического текста. Длина фразы —
главный из них: модель по умолчанию строит периоды на двадцать пять
слов с причастными оборотами, а живой автор рубит фразу короче.

ВАЖНО О РАЗБИЕНИИ НА ПРЕДЛОЖЕНИЯ. Наивное деление по точке на
юридическом тексте даёт неверные числа, и ошибка не мелкая. «Оно
предусмотрено ст. 1257 ГК РФ» наивный способ рвёт на две части, и
одно предложение средней длины превращается в два коротких. Пункты
списков («• Возмещение убытков») он тоже считает предложениями.
В сумме это завышало долю коротких фраз и занижало долю длинных —
на образце Коколова 38 % против настоящих 29 % и 6 % против 14 %.
Поэтому здесь: точки в сокращениях и числах защищены, пункты
списков вынесены в отдельный счёт.

Запуск:
    python3 tools/style-profile.py образец.txt [готовый_раздел.txt ...]
    python3 tools/style-profile.py --selftest

"""

from __future__ import annotations

import re
import statistics
import sys
from pathlib import Path

# Сокращения, после которых точка не кончает предложение. Отрицательный
# просмотр назад обязателен: без него «с» в списке матчит хвост слова
# «суд.», точка защищается, и два предложения слипаются в одно.
ABBR = (
    r"(?<![А-Яа-яЁёA-Za-z])"
    r"(?:ст|стт|п|пп|ч|абз|гл|разд|подп|г|гг|в|вв|руб|коп|тыс|млн|млрд"
    r"|см|ср|напр|рис|табл|стр|с|изд|им|др|пр|т|е|д)\."
)
SENTENCE_BREAK = re.compile(
    r"(?<=[.!?\u2026])[ \t]+(?=[«\"\'(\[]?[А-ЯЁA-Z0-9•])"
)
INITIAL = re.compile(r"(?<![А-Яа-яЁёA-Za-z])([А-ЯЁA-Z])\.")
BULLET = re.compile(r"^(?:[•\-–—*]|\d+[).]\s)")
_GUARD = "\x00"


def split_sentences(text: str) -> list[str]:
    """Делит текст на предложения, не спотыкаясь о «ст. 15» и «1,5 раза»."""
    guarded = re.sub(
        ABBR, lambda m: m.group(0).replace(".", _GUARD), text, flags=re.IGNORECASE
    )
    guarded = re.sub(
        r"(\d)\.(\d)", lambda m: m.group(1) + _GUARD + m.group(2), guarded
    )
    # Инициалы: «В.Н. Кудрявцев» — не два предложения, а одно имя.
    # Без этой защиты обрывки «В.» и «Н.» попадали в счёт как
    # короткие фразы и завышали долю коротких.
    guarded = re.sub(INITIAL, lambda m: m.group(1) + _GUARD, guarded)
    # Абзац — всегда граница предложения.
    #
    # Без этого «...в общественных отношениях [1].\n\nВ юридической
    # науке...» считалось одним предложением: выражение для границы
    # требует пробела или табуляции, а между абзацами стоит перенос.
    # На тексте из тринадцати кусков так склеивалось двадцать шесть
    # предложений из восьмидесяти четырёх — доля коротких фраз
    # выходила втрое меньше настоящей, а средняя длина фразы
    # завышалась.
    parts: list[str] = []
    for para in re.split(r"\n+", guarded):
        parts.extend(SENTENCE_BREAK.split(para))

    return [p.replace(_GUARD, ".").strip() for p in parts if p.strip()]


def is_bullet(sentence: str) -> bool:
    """Пункт списка — не фраза: мерить его длину вместе с прозой нельзя."""
    return bool(BULLET.match(sentence.strip()))


CLERICAL = [
    r"(?<![А-Яа-яЁё])осуществля(?:ется|ются)",
    r"(?<![А-Яа-яЁё])явля(?:ется|ются)",
    r"(?<![А-Яа-яЁё])данн(?:ый|ая|ое|ым|ого|ой|ом|ую)(?![А-Яа-яЁё])",
    r"(?<![А-Яа-яЁё])указанн(?:ый|ая|ое|ым|ого|ой|ом|ую|ые|ых)",
    r"(?<![А-Яа-яЁё])в целях(?![А-Яа-яЁё])",
    r"(?<![А-Яа-яЁё])в рамках(?![А-Яа-яЁё])",
    r"(?<![А-Яа-яЁё])необходимо отметить",
    # «представляется» канцелярит только как вводное: «представляется,
    # что». «Заявление представляется в суд» — обычная речь юриста.
    r"(?<![А-Яа-яЁё])представляется(?=,|\s+(?:целесообразн|необходим|возможн|обоснованн|что))",
    r"(?<![А-Яа-яЁё])вышеуказанн",
    r"(?<![А-Яа-яЁё])в настоящее время(?![А-Яа-яЁё])",
]


def profile(text: str) -> dict[str, float]:
    pieces = [s for s in split_sentences(text) if len(s) > 15]
    prose = [s for s in pieces if not is_bullet(s)]
    if not prose:
        return {}

    lengths = [len(s.split()) for s in prose]
    clerical = sum(
        len(re.findall(pattern, text, re.IGNORECASE)) for pattern in CLERICAL
    )

    per_100 = 100 / len(prose)
    return {
        "предложений": len(prose),
        "из них пунктов списка": len(pieces) - len(prose),
        "медиана слов": statistics.median(lengths),
        "среднее слов": round(statistics.mean(lengths), 1),
        # Разброс важнее среднего. Живой автор чередует рубленую фразу
        # с длинным периодом, модель выравнивает всё к середине — и
        # средние у них совпадают при совершенно разном звучании.
        "разброс длины": round(
            statistics.pstdev(lengths), 1) if len(lengths) > 1 else 0.0,
        "коротких ≤8 слов, %": round(
            100 * sum(1 for n in lengths if n <= 8) / len(lengths), 1),
        "длинных ≥25 слов, %": round(
            100 * sum(1 for n in lengths if n >= 25) / len(lengths), 1),
        "«например» на 100": round(
            len(re.findall(r"[Нн]апример", text)) * per_100, 1),
        "ссылок на нормы на 100": round(
            len(re.findall(r"ст\.\s*\d+", text)) * per_100, 1),
        "скобочных пояснений на 100": round(
            len(re.findall(r"\([^)]{10,80}\)", text)) * per_100, 1),
        "канцелярит на 100": round(clerical * per_100, 1),
    }


def selftest() -> int:
    """Проверяет ровно те случаи, на которых ошибался прежний замер."""
    checks = [
        ("Оно предусмотрено ст. 1257 ГК РФ. Это важно.", 2,
         "точка в «ст. 1257» не кончает предложение"),
        ("Срок — 1,5 года. Дальше суд.", 2, "запятая в числе не мешает"),
        ("Иск подан в суд. Суд его принял.", 2,
         "«суд.» не принят за сокращение «с.»"),
        ("Это так. • Признание права. • Возмещение убытков.", 1,
         "пункты списка не считаются прозой"),
        ("Вопрос решён? Да. Нет!", 3, "вопрос и восклицание делят текст"),
    ]
    bad = 0
    for text, expected, why in checks:
        pieces = [s for s in split_sentences(text) if len(s) > 1]
        got = len([s for s in pieces if not is_bullet(s)])
        ok = got == expected
        bad += not ok
        print(f"  {'✓' if ok else '✗'} {why}: ждали {expected}, вышло {got}")
    print("самопроверка пройдена" if not bad else f"ОШИБОК: {bad}")
    return 1 if bad else 0


def main(paths: list[str]) -> int:
    if paths and paths[0] == "--selftest":
        return selftest()
    if not paths:
        print(__doc__)
        return 1

    profiles = []
    for path in paths:
        text = Path(path).read_text(encoding="utf-8")
        p = profile(text)
        if not p:
            print(f"{path}: текста слишком мало")
            continue
        profiles.append((Path(path).name, p))

    if not profiles:
        return 1

    keys = list(profiles[0][1])
    width = max(len(k) for k in keys) + 2
    header = " " * width + "".join(f"{name[:14]:>16}" for name, _ in profiles)
    print(header)
    print("-" * len(header))
    for key in keys:
        row = f"{key:{width}}"
        for _, p in profiles:
            row += f"{p.get(key, 0):>16}"
        print(row)

    if len(profiles) > 1:
        print(
            "\nПервый столбец — образец. Чем ближе к нему остальные, тем "
            "лучше воспроизведён стиль.\nСамый показательный признак — "
            "доля длинных фраз: именно они выдают машинный текст."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
